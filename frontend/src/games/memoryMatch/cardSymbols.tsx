export const CARD_SYMBOLS_MAP = new Map<string, CardSymbolDefinition>(
  CARD_SYMBOLS.map((s) => [s.id, s])
);

export function getCardSymbol(id: string): CardSymbolDefinition {
  return CARD_SYMBOLS_MAP.get(id) || CARD_SYMBOLS[0];
}
